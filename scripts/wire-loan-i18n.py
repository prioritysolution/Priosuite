def replace_colon_label_nodes(text: str) -> str:
    for eng in sorted(COLON_LABELS, key=len, reverse=True):
        # keys may be without trailing space in smap
        key_eng = eng if eng in smap else eng.rstrip()
        if key_eng not in smap and eng not in smap:
            # try with trailing space variants
            candidates = [eng, eng.rstrip(), eng + " ", eng.rstrip() + " "]
            key_eng = next((c for c in candidates if c in smap), None)
            if not key_eng:
                continue
        te = t_jsx(key_eng if key_eng in smap else eng)
        text = re.sub(
            rf"(>)\s*{re.escape(eng)}\s*(<)",
            rf"\1{te}\2",
            text,
        )
    return text


def process_file(path: Path, also: list[str] | None = None):
    text = path.read_text(encoding="utf-8")
    text = ensure_import(text)
    names = [m.group(1) for m in re.finditer(r"const\s+([A-Z]\w*)\s*=\s*\(", text)]
    text = ensure_hook(text, also or names)
    text = replace_quoted_attrs(text)
    text = replace_between_tags(text)
    text = replace_toasts(text)
    text = replace_button_children(text)
    text = replace_safe_phrases(text)
    text = replace_generated_by(text)
    text = replace_exact_jsx_text_nodes(text, COLLECTION_LABELS + SAFE_PHRASE_REPLACES)
    text = replace_colon_label_nodes(text)
    # Subtotal / Grand Total / Total already via TableCell/tags
    # Fix accidental documentTitle stringification — leave documentTitle as plain English
    text = re.sub(
        r'documentTitle:\s*t\("loan\.[^"]+"\)',
        lambda m: m.group(0),  # keep if already t() without quotes — ok
        text,
    )
    if '"{t(' in text or "class{t(" in text or "head{t(" in text:
        print("  WARN corruption markers in", path.name)
    path.write_text(text, encoding="utf-8")
    print("ok", path.relative_to(ROOT).as_posix())


def main():
    for p in sorted(ROOT.rglob("*.jsx")):
        also = None
        if p.name == "index.jsx" and "newApplication" in str(p):
            also = ["ResponsiveTable", "NewApplication"]
        process_file(p, also)


if __name__ == "__main__":
    main()
