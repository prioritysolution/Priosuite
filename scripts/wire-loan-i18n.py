def replace_exact_jsx_text_nodes(text: str, phrases: list[str]) -> str:
    for eng in sorted(phrases, key=len, reverse=True):
        if eng not in smap:
            continue
        te = t_jsx(eng)
        text = re.sub(
            rf"(>)\s*{re.escape(eng)}\s*(<)",
            rf"\1{te}\2",
            text,
        )
        # multiline indented text node
        text = re.sub(
            rf"^(\s+){re.escape(eng)}(\s*)$",
            rf"\1{te}\2",
            text,
            flags=re.M,
        )
    return text


