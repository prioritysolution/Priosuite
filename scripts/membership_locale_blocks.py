def _js_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def dict_to_js(obj, level=2) -> str:
    """Serialize nested dict to JS object literal (2-space-ish project uses 2 spaces under translation)."""
    indent = "  " * level
    closer = "  " * (level - 1)
    if not isinstance(obj, dict):
        return f'"{_js_escape(str(obj))}"'
    lines = ["{"]
    items = list(obj.items())
    for i, (k, v) in enumerate(items):
        comma = "," if i < len(items) - 1 else ""
        if isinstance(v, dict):
            inner = dict_to_js(v, level + 1)
            lines.append(f"{indent}{k}: {inner}{comma}")
        else:
            lines.append(f'{indent}{k}: "{_js_escape(str(v))}"{comma}')
    lines.append(f"{closer}}}")
    return "\n".join(lines)


