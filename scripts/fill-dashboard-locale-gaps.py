def patch_dashboard(lang, updates):
    path = LOC / f"{lang}.js"
    text = path.read_text(encoding="utf-8")
    m = re.search(r"\n    dashboard:\s*\{", text)
    if not m:
        raise SystemExit(f"{lang}: no dashboard")
    depth = 0
    i = m.end() - 1
    start = m.start()
    while i < len(text):
        ch = text[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
        i += 1
    else:  # pragma: no cover
        raise SystemExit(f"{lang}: unclosed dashboard")

    block = text[start:end]
    n = 0
    for key, val in updates.items():
        esc = val.replace("\\", "\\\\").replace('"', '\\"')
        new_block, count = re.subn(
            rf'(\n      {re.escape(key)}:\s*")(?:(?:\\.|[^"\\])*)(")',
            rf"\g<1>{esc}\2",
            block,
            count=1,
        )
        if count:
            block = new_block
            n += 1
        else:
            print(f"  MISS {lang}.{key}")
    path.write_text(text[:start] + block + text[end:], encoding="utf-8")
    print(f"{lang}: updated {n}/{len(updates)} keys")


