def js_obj(obj, indent=4):
    """Convert Python dict/list/str to JS object literal (no JSON quotes on keys)."""
    sp = " " * indent

    def fmt(o, level):
        pad = " " * (indent * level)
        pad2 = " " * (indent * (level + 1))
        if isinstance(o, dict):
            if not o:
                return "{}"
            lines = ["{"]
            items = list(o.items())
            for i, (k, v) in enumerate(items):
                comma = "," if i < len(items) - 1 else ""
                lines.append(f"{pad2}{k}: {fmt(v, level + 1)}{comma}")
            lines.append(pad + "}")
            return "\n".join(lines)
        if isinstance(o, str):
            return json.dumps(o, ensure_ascii=False)
        raise TypeError(type(o))

    return fmt(obj, 1)


