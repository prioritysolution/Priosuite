def to_camel(s: str) -> str:
    s = s.strip()
    # placeholders
    if s.lower().startswith("enter "):
        rest = s[6:]
        parts = re.findall(r"[A-Za-z0-9]+", rest)
        if not parts:
            return "enter"
        return "enter" + "".join(p[:1].upper() + p[1:] for p in parts)
    if s.lower().startswith("select "):
        rest = s[7:]
        parts = re.findall(r"[A-Za-z0-9]+", rest)
        return "select" + "".join(p[:1].upper() + p[1:] for p in parts)
    if s.lower().startswith("search "):
        rest = s[7:].rstrip(".")
        parts = re.findall(r"[A-Za-z0-9]+", rest)
        return "search" + "".join(p[:1].upper() + p[1:] for p in parts)
    parts = re.findall(r"[A-Za-z0-9]+", s)
    if not parts:
        return "key"
    first = parts[0]
    first = first[:1].lower() + first[1:]
    return first + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def build_string_map(strings: list[str]) -> dict[str, str | tuple[str, str]]:
    used: dict[str, str] = {}  # flat key -> eng
    print_used: dict[str, str] = {}
    result: dict[str, str | tuple[str, str]] = {}
    skip = {"#", "0.00"}
    for eng in strings:
        if eng in skip:
            continue
        if "\n" in eng or "setIsOpen" in eng or "generatePDF" in eng or "setOpen" in eng or "setShow" in eng or "setDelete" in eng or "setSecurity" in eng:
            continue
        if eng in OVERRIDES:
            result[eng] = OVERRIDES[eng]
            continue
        # ALL CAPS-ish print headers (mostly uppercase letters)
        letters = re.sub(r"[^A-Za-z]", "", eng)
        if letters and letters == letters.upper() and len(eng) > 1 and eng not in (
            "ROI",
            "ECS Account",
            "EMI Amount",
            "CIF No.",
            "CIF. No.",
            "OD Interest",
            "OD Principal",
        ):
            key = to_camel(eng.lower().replace(".", " "))
            # ensure unique in print
            base = key
            i = 2
            while key in print_used and print_used[key] != eng:
                key = f"{base}{i}"
                i += 1
            print_used[key] = eng
            result[eng] = ("print", key)
            continue
        key = to_camel(eng)
        base = key
        i = 2
        while key in used and used[key] != eng:
            key = f"{base}{i}"
            i += 1
        used[key] = eng
        result[eng] = key
    return result


def load_strings() -> list[str]:
    p = Path(__file__).with_name("_loan_strings.json")
    return json.loads(p.read_text(encoding="utf-8"))


def build_en_tree(string_map: dict[str, str | tuple[str, str]]) -> dict:
    tree: dict = {"print": {}}
    for eng, key in string_map.items():
        if isinstance(key, tuple):
            tree["print"][key[1]] = eng
        else:
            tree[key] = eng
    # ensure toast key exists even if not in dump
    tree.setdefault("failedToDownloadPdf", "Failed to download PDF")
    tree.setdefault("loanRepaymentRegisterFrom", "Loan Repayment Register From")
    return tree


