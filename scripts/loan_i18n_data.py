def translate_tree(en_tree: dict, lang: str) -> dict:
    tr = {"hi": TR_HI, "bn": TR_BN, "or": TR_OR}[lang]

    def walk(node):
        if isinstance(node, dict):
            return {k: walk(v) for k, v in node.items()}
        if isinstance(node, str):
            return tr.get(node, node)
        return node

    return walk(en_tree)


